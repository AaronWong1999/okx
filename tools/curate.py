def safe(s):
    return re.sub(r'[\\/:*?"<>|\s]+', "_", s).strip("_")


def main():
    if ROOT.exists():
        shutil.rmtree(ROOT)
    ROOT.mkdir(parents=True)

    manifest, used, missing = [], set(), []
    for vid, frame, key, label in MAPPING:
        src = FULL / vid / f"{frame}.png"
        if not src.exists():
            missing.append(f"{vid}/{frame}.png")
            continue
        dest_dir = ROOT / FOLDERS[key]
        dest_dir.mkdir(parents=True, exist_ok=True)
        name = f"{VIDEO_LABEL[vid]}_{safe(label)}.png"
        dest = dest_dir / name
        n = 1
        while dest.exists():
            dest = dest_dir / f"{VIDEO_LABEL[vid]}_{safe(label)}_{n}.png"
            n += 1
        shutil.copy2(src, dest)
        used.add(f"{vid}/{frame}.png")
        manifest.append({
            "bot": FOLDERS[key],
            "file": dest.relative_to(ROOT).as_posix(),
            "label": label,
            "video": vid,
            "frame": frame,
        })

    all_frames = set()
    for vid in VIDEO_LABEL:
        for p in (FULL / vid).glob("*.png"):
            all_frames.add(f"{vid}/{p.name}")
    uncurated = sorted(all_frames - used)

    (ROOT / "manifest.json").write_text(json.dumps(
        {"source": "OKX app screen recordings, 2026-10-19", "shots": manifest},
        ensure_ascii=False, indent=1))

    print(f"wrote {len(manifest)} screenshots into {len(FOLDERS)} bot folders")
    if missing:
        print("MISSING sources:", *missing, sep="\n  ")
    print(f"\nuncurated extracted frames ({len(uncurated)}):")
    for u in uncurated:
        print("  ", u)
    print()
    for k, d in FOLDERS.items():
        n = len([m for m in manifest if m["bot"] == d])
        print(f"  {d:<42} {n:>3} shots")


if __name__ == "__main__":
    main()
